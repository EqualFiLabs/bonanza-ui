import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { artifact, contractsDirectory, root } from "./fork/shared.mjs";

// The facets a browser reaches. Cut, loupe and initializer surfaces stay out of the bundle.
const facets = [
  "GovernanceFacet",
  "LotteryFacet",
  "SettlementFacet",
  "ClaimsFacet",
  "RevenueFacet",
  "LotteryViewFacet",
  "BonanzaTokenFacet",
  "BonanzaStakingFacet",
  "BonanzaViewFacet",
];

const seen = new Set();
const abi = facets
  .flatMap((name) => artifact("lottery", name).abi)
  .filter((entry) => {
    if (!["function", "event", "error"].includes(entry.type)) return false;
    const key = `${entry.type}:${entry.name}:${entry.inputs.map((input) => input.type).join()}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });

const commit = spawnSync("git", ["rev-parse", "HEAD"], {
  cwd: contractsDirectory(),
  encoding: "utf8",
}).stdout.trim();

const lines = abi.map((entry) => `  ${JSON.stringify(entry)},`).join("\n");
const output = `// Generated by scripts/sync-abi.mjs from EqualFiLabs/bonanza at ${commit}. Do not edit.
export const lotteryAbi = [
${lines}
] as const;
`;
writeFileSync(resolve(root, "lib/contracts/generated/lottery.ts"), output);
console.log(`Wrote ${abi.length} ABI entries from ${commit.slice(0, 7)}.`);
